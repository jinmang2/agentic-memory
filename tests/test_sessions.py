def test_episodes_carry_provenance_and_render_orders_steps(codex_session):
    traj = load_codex(codex_session)
    episodes = traj.to_episodes(namespace="ns")
    assert [e.role for e in episodes] == [s.kind for s in traj.steps]
    assert all(e.namespace == "ns" for e in episodes)
    first = episodes[0].meta
    assert first["source"] == HOST_CODEX and first["session_id"] == "019f-session"
    assert first["step_index"] == 0 and first["cwd"] == "/home/u/other"
    rendered = traj.render()
    assert (
        rendered.index("[0] USER")
        < rendered.index("[1] TOOL_CALL(exec)")
        < rendered.index("[4] ASSISTANT")
    )
    assert len(traj.render(max_chars=120)) < 200


@pytest.mark.parametrize(
    "raw",
    [
        "token sk-proj-ABCDEFGHIJKLMNOPQRSTUVWXYZ",
        "Authorization: Bearer abcdefghijklmnopqrstuvwxyz0123",
        "export OPENAI_API_KEY=abcdefghijklmnopqrstuvwxyz",
        "-----BEGIN RSA PRIVATE KEY-----\nMIIE\n-----END RSA PRIVATE KEY-----",
        "xoxb-1234567890-abcdefghij",
    ],
)
def test_common_credential_shapes_are_redacted(raw):
    out = redact_secrets(raw)
    assert REDACTED in out
    assert "abcdefghijklmnopqrstuvwxyz" not in out and "MIIE" not in out


