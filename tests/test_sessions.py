def _jsonl(path, records):
    path.write_text("\n".join(json.dumps(r, ensure_ascii=False) for r in records) + "\n")
    return path


def _cc(kind, content, **extra):
    base = {
        "type": kind,
        "uuid": "u",
        "parentUuid": None,
        "isSidechain": False,
        "timestamp": TS,
        "cwd": "/home/u/proj",
        "sessionId": "sess-1",
        "version": "2.1.225",
        "gitBranch": "main",
        "message": {"role": kind, "content": content},
    }
    base.update(extra)
    return base


