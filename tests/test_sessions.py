def test_claude_code_keeps_the_conversation_and_drops_the_harness(claude_session):
    traj = load_claude_code(claude_session)
    assert traj.host == HOST_CLAUDE_CODE
    assert traj.id == "abc123"
    assert traj.cwd == "/home/u/proj" and traj.git_branch == "main"
    kinds = [s.kind for s in traj.steps]
    assert kinds == ["user", "assistant", "tool_call", "tool_result", "assistant"]
    user = traj.steps[0].text
    assert user == "Please fix the failing test"  # reminder + command wrapper stripped
    assert "private reasoning" not in traj.render()  # thinking dropped
    assert "sidechain chatter" not in traj.render()  # sub-agent chain dropped
    assert "Caveat" not in traj.render()  # isMeta dropped


def test_claude_code_tool_steps_are_linked_named_clipped_and_redacted(claude_session):
    traj = load_claude_code(claude_session)
    call, result = traj.steps[2], traj.steps[3]
    assert call.tool_name == "Bash" and call.tool_call_id == "toolu_1"
    assert "pytest -q" in call.text
    assert "sk-abcdefghijklmnopqrstuvwxyz1234" not in call.text and REDACTED in call.text
    assert result.tool_name == "Bash" and result.tool_call_id == "toolu_1"
    assert len(result.text) <= TOOL_OUTPUT_MAX_CHARS + 40 and "chars omitted" in result.text
    assert result.meta == {"is_error": False}
    assert "AKIAABCDEFGHIJKLMNOP" not in traj.steps[4].text


